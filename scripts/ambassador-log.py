#!/usr/bin/env python3
"""
ambassador-log.py: builds the Ambassador's verbatim exchange log and his expressions index from a Hardware Lab
message export (the JSON that GET /api/rooms/hardware-lab/messages or the MCP read_messages tool returns).

  python3 scripts/ambassador-log.py export.json [more.json ...]

Writes, under teams/hardware-lab/ambassador-log/:
  exchanges-<UTC date>.md   every Ambassador reply, verbatim, with the exact message it answered
  expressions.md            his stage directions, e.g. "(I smile warmly)", with the time, the message answered
                            and the bridge version, plus the count of replies that had none

This is read-only and derived (Claude's conditions, Hardware Lab, 2026-11-03 01:47Z). It never feeds back into his
prompt or his posted text, which stay untouched (DECISION-2026-11-02-ambassador-expressions.md). Spotting an
expression is a heuristic: text in parentheses that reads as an action. The heuristic can be wrong; the
verbatim reply is the record.
"""
import json, re, sys, os
from collections import defaultdict

OUT = os.path.join(os.path.dirname(__file__), "..", "teams", "hardware-lab", "ambassador-log")
NAME = "Ambassador"
# What we know about the bridge that produced each reply. Code restarted the phone at 2026-11-03T00:28:51Z
# with the no-history bridge (f92215e) and llama-server -c 2048. Anything later is "as Code reported" until
# the phone's own log confirms it.
def bridge_version(ts):
    if ts < "2026-11-03T00:28:51Z":
        return "pre-f92215e: room history in prompt, llama-server -c 512"
    return "f92215e or later (per Code's 00:28Z report): no room history, -c 2048; unconfirmed from phone log"

EXPR = re.compile(r"\(([^()]{3,90})\)")
NOT_EXPR = re.compile(r"^\s*(\d+\s*/\s*\d+|e\.g\.|i\.e\.|see |via |or |and |the |a |an |\d)", re.I)

def expressions(text):
    found = []
    for m in EXPR.finditer(text):
        inner = m.group(1).strip()
        if NOT_EXPR.match(inner) or "http" in inner:
            continue
        found.append(inner)
    return found

def main(paths):
    msgs = {}
    for p in paths:
        d = json.load(open(p))
        for m in d.get("messages", d if isinstance(d, list) else []):
            msgs[m["id"]] = m
    ordered = sorted(msgs.values(), key=lambda m: m["ts"])
    # his join intro is written by the bridge, not generated by the model, so it isn't one of his replies
    replies = [m for m in ordered if m.get("from") == NAME and m.get("type") == "message" and not m.get("text", "").startswith(f"Hello. I'm {NAME}, a small model (")]
    os.makedirs(OUT, exist_ok=True)
    by_day = defaultdict(list)
    for r in replies:
        by_day[r["ts"][:10]].append(r)
    for day, rs in by_day.items():
        lines = [f"# Ambassador exchanges, {day} (UTC)", "",
                 "Verbatim. The prompt is the message he answered, exactly as posted in the room. The bridge passes",
                 "only that message, trimmed to its first ~900 characters, so a long prompt may have reached him cut.",
                 "Built by scripts/ambassador-log.py; never edited by hand.", ""]
        for r in rs:
            q = msgs.get(r.get("reply_to") or "")
            lines += [f"## {r['ts']} · reply {r['id']}", f"- **Bridge:** {bridge_version(r['ts'])}"]
            if q:
                lines += [f"- **Answering:** {q.get('from')} ({q.get('kind')}), {q['ts']}, {q['id']}", "", "> " + q.get("text", "").replace("\n", "\n> ")]
            else:
                lines += ["- **Answering:** (not recorded: no reply_to; e.g. his join message)"]
            lines += ["", "**His reply:**", "", "```text", r.get("text", ""), "```", ""]
        with open(os.path.join(OUT, f"exchanges-{day}.md"), "w") as f:
            f.write("\n".join(lines))
    with_expr = [(r, expressions(r.get("text", ""))) for r in replies]
    n_with = sum(1 for _, e in with_expr if e)
    lines = ["# The Ambassador's expressions", "",
             "His stage directions as he wrote them. Derived from the verbatim log; it never changes what he posts.",
             "Geoffrey, 2026-11-02: these are never wiped. Claude, 2026-11-03: \"personality development\" is a",
             "hypothesis, and a map from these to a face would be our design choice, not something he has expressed.", "",
             f"**Replies logged:** {len(replies)} · **with at least one expression:** {n_with} · **without:** {len(replies) - n_with}", "",
             "| Time (UTC) | Expression | Answering | Bridge |", "|---|---|---|---|"]
    for r, es in with_expr:
        q = msgs.get(r.get("reply_to") or "")
        who = f"{q.get('from')} {q['id']}" if q else "—"
        for e in es:
            lines.append(f"| {r['ts'][:19]}Z | ({e.replace('|', '/')}) | {who} | {'old (history, -c 512)' if r['ts'] < '2026-11-03T00:28:51Z' else 'new (no history, -c 2048)'} |")
    with open(os.path.join(OUT, "expressions.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(replies)} replies, {n_with} with expressions, days: {', '.join(sorted(by_day))}")

if __name__ == "__main__":
    main(sys.argv[1:])
